def style_sheet(ws, headers, rows_data):
    ws.append(headers)
    for col_idx in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=col_idx)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    
    for r_idx, r_data in enumerate(rows_data, start=2):
        ws.append(r_data)
        for c_idx in range(1, len(r_data) + 1):
            cell = ws.cell(row=r_idx, column=c_idx)
            cell.font = ROW_FONT
            cell.border = THIN_BORDER
            val = str(cell.value or "")
            if val.startswith("http://") or val.startswith("https://"):
                cell.font = LINK_FONT
                cell.hyperlink = val
            elif val in ["HEALTHY", "YES", "LOW", "NONE", "COMPLETED", "REPAIRED"]:
                cell.font = Font(name="Calibri", size=10, bold=True, color="006100")
            elif val in ["PARTIAL", "MEDIUM", "WARNING", "NEEDS_REVIEW"]:
                cell.font = Font(name="Calibri", size=10, bold=True, color="9C6500")
            elif val in ["BROKEN", "HIGH", "BLOCKED"]:
                cell.font = Font(name="Calibri", size=10, bold=True, color="9C0006")
                
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions
    
    # Auto-adjust column widths
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            val_str = str(cell.value or "")
            if "\n" in val_str:
                val_str = max(val_str.split("\n"), key=len)
            max_len = max(max_len, len(val_str))
        ws.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 50)

